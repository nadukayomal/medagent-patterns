class ToolRegistry:
    """
    A registry to manage, store, and execute tools (functions) available to the AI agents.
    
    This class maps string names of tools (as requested by the LLM) to actual Python callable functions.
    It facilitates the execution phase of the 'Tool Use' and 'ReAct' design patterns.
    """
    
    def __init__(self):
        """
        Initializes an empty registry.
        
        Args:
            None
        """
        # The internal dictionary mapping tool names to their corresponding Python functions
        self._registered_tools: Dict[str, Callable] = {}

    def register_tool(self, tool_name: str, tool_function: Callable) -> None:
        """
        Registers a new tool in the registry, making it available for execution.

        Args:
            tool_name (str): The unique string identifier for the tool (should match the name in the JSON schema).
            tool_function (Callable): The actual Python function to execute when the tool is called.

        Returns:
            None
        """
        self._registered_tools[tool_name] = tool_function
        print(f"DEBUG: Successfully registered tool '{tool_name}'")

    def execute_tool(self, tool_name: str, tool_arguments: Dict[str, Any]) -> Any:
        """
        Executes a registered tool using the arguments provided by the LLM.

        Args:
            tool_name (str): The name of the tool to execute.
            tool_arguments (Dict[str, Any]): A dictionary of arguments parsed from the LLM's tool call request.

        Returns:
            Any: The result of the executed function. Typically converted to a string or JSON later.
            
        Raises:
            ValueError: If the requested tool_name is not found in the registry.
        """
        # Complex Logic Explanation:
        # When the LLM decides to use a tool, it returns the name of the tool and a JSON string of arguments.
        # After parsing those arguments into a Python dictionary, we use this method to look up the actual
        # Python function in our '_registered_tools' dictionary. We then unpack the arguments dictionary 
        # using the '**' operator, passing them as keyword arguments to the target function.
        # We catch any potential missing tools to prevent system crashes during the autonomous loops.
        
        if tool_name not in self._registered_tools:
            raise ValueError(f"Tool '{tool_name}' is not registered in the ToolRegistry.")
            
        target_function = self._registered_tools[tool_name]
        
        # Execute the function by unpacking the arguments dictionary
        try:
            execution_result = target_function(**tool_arguments)
            return execution_result
        except Exception as execution_error:
            # In a robust system, we might want to return the error back to the LLM so it can reflect and fix it
            return f"Error executing tool {tool_name}: {str(execution_error)}"

    def get_available_tools(self) -> List[str]:
        """
        Retrieves a list of the names of all currently registered tools.

        Args:
            None

        Returns:
            List[str]: A list containing the string identifiers of all available tools.
        """
        return list(self._registered_tools.keys())
