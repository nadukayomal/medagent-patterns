"""
Large Language Model (LLM) Utilities Module.

This module defines the core interfaces and concrete implementations for interacting with various
LLM providers such as OpenRouter and OpenAI. It employs the Strategy and Factory design patterns 
to ensure a consistent interface across different services (adhering to SOLID principles).

It includes a base class (`LLMProvider`) to define the contract, specific implementations for 
different providers, and a `ToolRegistry` class to manage and execute tools (functions) that 
the LLMs can call as part of the 'Tool Use' and 'ReAct' design patterns.

Overall, it handles text generation, coordinates tool calling capabilities, and abstracts away
the complexities of direct API interaction.
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any, Callable, Optional
import json


class LLMProvider(ABC):
    """
    Abstract Base Class representing a generic LLM Provider.
    
    This class enforces a standard interface for any language model provider (e.g., OpenAI, Anthropic, 
    OpenRouter) integrated into the Agentic RAG system.
    """

    @abstractmethod
    def generate(self, messages: List[Dict[str, Any]], model: str, **kwargs) -> str:
        """
        Generates a standard text response from the language model based on the provided messages.

        Args:
            messages (List[Dict[str, Any]]): The conversation history formatted as a list of dictionaries 
                                             (e.g., [{"role": "user", "content": "Hello"}]).
            model (str): The specific model identifier to be used (e.g., "gpt-4").
            **kwargs: Additional parameters such as temperature, max_tokens, etc.

        Returns:
            str: The generated text response from the language model.
        """
        pass

    @abstractmethod
    def generate_with_tools(self, messages: List[Dict[str, Any]], model: str, tools: List[Dict[str, Any]], **kwargs) -> Any:
        """
        Generates a response from the language model, giving it the ability to invoke external tools.

        Args:
            messages (List[Dict[str, Any]]): The conversation history.
            model (str): The specific model identifier to be used.
            tools (List[Dict[str, Any]]): A list of tool definitions (usually JSON schema) describing 
                                          what functions the model can call.
            **kwargs: Additional parameters such as temperature, tool_choice, etc.

        Returns:
            Any: The response from the model, which could be a standard text message or a structured 
                 tool call request.
        """
        pass


